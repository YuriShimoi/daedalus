// Bundles every SVG in this folder into ../icons.js (an inline sprite), so pages need no
// CDN, web font or path outside the project. Run: npm run icons
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const symbols = fs.readdirSync(dir).filter(f => f.endsWith('.svg')).sort().map(f => {
  const svg = fs.readFileSync(path.join(dir, f), 'utf8');
  const box = svg.match(/viewBox="([^"]+)"/)[1];
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').trim().replace(/^.*?<svg[^>]*>|<\/svg>\s*$/g, '').replace(/ fill="currentColor"/g, '');
  return `<symbol id="i-${f.slice(0, -4)}" viewBox="${box}">${body}</symbol>`;
});

const out = `// Generated by shared/icons/build.js from Font Awesome Free (shared/icons/LICENSE.txt) and Phosphor Icons (LICENSE-phosphor.txt, chest). Do not edit.
(DAE => {
  const SPRITE = '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">'
${symbols.map(s => `    + '${s}'`).join('\n')}
    + '</svg>';

  class Icons {
    static sprite = SPRITE;

    /** Adds the sprite to the page once. */
    static mount(doc = document) {
      if(doc.getElementById('dae-sprite')) return;
      const $box = doc.createElement('div');
      $box.id = 'dae-sprite';
      $box.style.cssText = 'position:absolute;width:0;height:0;overflow:hidden';
      $box.innerHTML = SPRITE;
      doc.body.prepend($box);
    }

    /** Markup for one icon, e.g. Icons.html('key'). */
    static html(name, cls = '') {
      return \`<svg class="ic \${cls}" aria-hidden="true"><use href="#i-\${name}"/></svg>\`;
    }
  }

  DAE.Icons = Icons;
})(globalThis.DAE ??= {});
if(typeof module === 'object') module.exports = globalThis.DAE;
`;
fs.writeFileSync(path.join(dir, '..', 'icons.js'), out);
console.log(`${symbols.length} icons -> shared/icons.js`);
